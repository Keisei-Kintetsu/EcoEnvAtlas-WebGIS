let optLang = localStorage.getItem("rsei-viewer-lang") || "zh_cn";

const optEl = {
  language: document.querySelector("#languageSelect"),
};

function optT(key) {
  return OPT_I18N[optLang]?.[key] ?? OPT_I18N.zh_cn[key] ?? key;
}

function optSet(id, value) {
  const node = document.querySelector(`#${id}`);
  if (node) node.textContent = value;
}

function optRenderParagraphs(id, items) {
  const node = document.querySelector(`#${id}`);
  if (node) node.innerHTML = items.map((text) => `<p>${text}</p>`).join("");
}

function optRenderList(id, items) {
  const node = document.querySelector(`#${id}`);
  if (node) node.innerHTML = items.map((text) => `<li>${text}</li>`).join("");
}

function renderOpticalPage() {
  document.documentElement.lang = optLang === "zh_hant" ? "zh-Hant" : optLang === "zh_cn" ? "zh-Hans" : "en";
  document.title = optT("pageTitle");

  ["navFusion", "navAnalysis", "navPca", "navBackground", "navOptical", "navLst", "navStack", "navTeam"].forEach((id) => {
    optSet(id, optT(id));
  });

  optSet("optEyebrow", optT("eyebrow"));
  optSet("optTitle", optT("title"));
  optSet("optSubtitle", optT("subtitle"));
  optSet("optSection1Title", optT("section1Title"));
  optRenderParagraphs("optSection1Body", optT("section1Body"));
  optSet("optSection2Title", optT("section2Title"));
  optRenderList("optSection2List", optT("section2List"));
  optSet("optSection3Title", optT("section3Title"));
  optRenderParagraphs("optSection3Body", optT("section3Body"));
  optSet("optSection4Title", optT("section4Title"));
  optRenderList("optSection4List", optT("section4List"));
  optSet("optSection5Title", optT("section5Title"));
  optSet("optCaption1", optT("caption1"));
  optSet("optCaption2", optT("caption2"));
  optSet("optCaption3", optT("caption3"));
  optSet("optSection6Title", optT("section6Title"));
  optRenderParagraphs("optSection6Body", optT("section6Body"));
}

if (optEl.language) {
  optEl.language.value = optLang;
  optEl.language.addEventListener("change", () => {
    optLang = optEl.language.value;
    localStorage.setItem("rsei-viewer-lang", optLang);
    renderOpticalPage();
  });
}

renderOpticalPage();
